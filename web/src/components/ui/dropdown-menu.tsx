/*
 * shadcn's dropdown menu, with the highlight colours re-pointed at this
 * palette.
 *
 * Every interactive state shadcn generates is keyed to `--accent`, and this
 * site maps `--accent` and `--popover` to the same token (`--surface`,
 * #121214) because it has no accent colour to spare. The stock file therefore
 * ships a menu whose keyboard focus and hover states are exactly the colour
 * of the menu they sit in — invisible, and worst for the person who most
 * needs them, since a pointer user still has the cursor to go on. The
 * separator had the same problem via `bg-muted`.
 *
 * So the highlights are a 10% wash of the ink instead: light on the dark
 * theme, dark on the light one (#247; it was white, which only worked dark). Emphasis on this site is value, never hue.
 */
import * as React from "react"
import * as DropdownMenuPrimitive from "@radix-ui/react-dropdown-menu"
import { Check, ChevronRight, Circle } from "lucide-react"

import { cn } from "@/lib/utils"

const DropdownMenu = DropdownMenuPrimitive.Root

const DropdownMenuTrigger = DropdownMenuPrimitive.Trigger

const DropdownMenuGroup = DropdownMenuPrimitive.Group

const DropdownMenuPortal = DropdownMenuPrimitive.Portal

const DropdownMenuSub = DropdownMenuPrimitive.Sub

const DropdownMenuRadioGroup = DropdownMenuPrimitive.RadioGroup

const DropdownMenuSubTrigger = React.forwardRef<
  React.ElementRef<typeof DropdownMenuPrimitive.SubTrigger>,
  React.ComponentPropsWithoutRef<typeof DropdownMenuPrimitive.SubTrigger> & {
    inset?: boolean
  }
>(({ className, inset, children, ...props }, ref) => (
  <DropdownMenuPrimitive.SubTrigger
    ref={ref}
    className={cn(
      "flex cursor-default select-none items-center gap-2 rounded-sm px-2 py-1.5 text-sm outline-none focus:bg-ink/10 focus:text-bone data-[state=open]:bg-ink/10 [&_svg]:pointer-events-none [&_svg]:size-4 [&_svg]:shrink-0",
      inset && "ps-8",
      className
    )}
    {...props}
  >
    {children}
    <ChevronRight className="ms-auto rtl:-scale-x-100" />
  </DropdownMenuPrimitive.SubTrigger>
))
DropdownMenuSubTrigger.displayName =
  DropdownMenuPrimitive.SubTrigger.displayName

