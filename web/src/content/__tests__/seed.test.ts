import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { links } from "@/data/links";
import { projects } from "@/data/projects";
import { about, contact, footer, heroPhrases, plate, plateTitle } from "@/data/site";
import { buildStory } from "@/data/story";
import { localize, seedBundle } from "../convert";
import {
  CONTENT_KEYS,
  ProjectsContentSchema,
  SiteCopySchema,
  StoryContentSchema,
  checkContent,
} from "../schema";

/*
 * The content store's seed (#163), held to the data files.
 *
 * `backend/src/content/seed.ts` is what the store starts as, and
 * `seedBundle()` is what the site renders without the API. They have to be
 * the same bytes, or the switch to the store changes the page, so the backend
 * file is this suite's output: run with UPDATE_SEED=1 to rewrite it after
 * editing a data file, and the suite fails until someone has.
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = (p: string) => resolve(HERE, "../../../..", p);
const SEED_FILE = ROOT("backend/src/content/seed.ts");

function renderSeed(): string {
  return [
    "/*",
    " * GENERATED by web/src/content/__tests__/seed.test.ts from web/src/data/*.ts.",
    " * Do not edit by hand: change the data file and run",
    " *   (cd web && UPDATE_SEED=1 npx vitest run src/content/__tests__/seed.test.ts)",
    " *",
    " * The content store's first state (#163). The seed writes it only where a",
    " * document does not exist yet, so an edit made in the admin is never",
    " * overwritten by it.",
    " */",
    `export const CONTENT_SEED: unknown = ${JSON.stringify(seedBundle(), null, 2)};`,
    "",
  ].join("\n");
}

describe("the content seed", () => {
  it("is valid under every schema and every save-time rule", () => {
    const b = seedBundle();
    expect(ProjectsContentSchema.safeParse(b.projects).error).toBeUndefined();
    expect(StoryContentSchema.safeParse(b.story).error).toBeUndefined();
    expect(SiteCopySchema.safeParse(b.siteCopy).error).toBeUndefined();
    for (const key of CONTENT_KEYS) expect(checkContent(b, key)).toEqual([]);
  });

  it("is what the backend seeds the store with", () => {
    const want = renderSeed();
    if (process.env.UPDATE_SEED) writeFileSync(SEED_FILE, want);
    expect(readFileSync(SEED_FILE, "utf8")).toBe(want);
  });

  it("parses back to exactly the data files", () => {
    const v = localize(seedBundle(), "en");
    expect(v.projects).toEqual(projects);
    expect(v.site.plate).toEqual(plate);
    expect(v.site.plateTitle).toEqual(plateTitle);
    expect(v.site.heroPhrases).toEqual(heroPhrases);
    expect(v.site.about).toEqual(about);
    expect(v.site.contact).toEqual(contact);
    expect(v.site.links).toEqual(links);
    expect(v.site.footer).toEqual(footer);
    const s = v.story;
    expect(buildStory(v.projects, s.lines, s.images, s.interludes, s.layouts, s.hand)).toEqual(buildStory());
  });

  it("falls back to English per field when a Hebrew one is absent", () => {
    const b = seedBundle();
    b.siteCopy.hero.phrases[1] = { en: "Product builder", he: "בונה מוצרים" };
    const he = localize(b, "he").site.heroPhrases;
    expect(he[0]).toBe("Technology");
    expect(he[1]).toBe("בונה מוצרים");
    expect(localize(b, "en").site.heroPhrases[1]).toBe("Product builder");
  });

  it("keeps the web's schema a copy of the backend's", () => {
    const backend = readFileSync(ROOT("backend/src/schemas/site-content.ts"), "utf8");
    const web = readFileSync(ROOT("web/src/content/schema.ts"), "utf8");
    const body = (src: string, marker: string) => src.slice(src.indexOf(marker) + marker.length);
    expect(body(web, "// ---- copy below ----\n")).toBe(body(backend, 'import { SlugSchema } from "./content.js";\n'));
  });
});
